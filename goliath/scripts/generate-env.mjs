#!/usr/bin/env node
/**
 * Generates the GOLIATH secrets that can be created locally and writes
 * goliath/.env.local. Credentials that require your own cloud accounts
 * (Supabase project, Google OAuth client) are written empty so that
 * scripts/check-env.mjs fails loudly instead of booting a half-configured app.
 *
 * Usage:  node scripts/generate-env.mjs [--force]
 */
import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const target = join(root, ".env.local");
const templatePath = join(root, ".env.example");

if (existsSync(target) && !process.argv.includes("--force")) {
  console.log(".env.local already exists. Re-run with --force to overwrite.");
  process.exit(0);
}

if (!existsSync(templatePath)) {
  console.error("Missing .env.example template");
  process.exit(1);
}

const encryptionKey = randomBytes(32).toString("base64");

// Values the operator must supply from their own cloud accounts.
const blank = new Set([
  "NEXT_PUBLIC_SUPABASE_URL",
  "NEXT_PUBLIC_SUPABASE_ANON_KEY",
  "SUPABASE_SERVICE_ROLE_KEY",
  "GOOGLE_CLIENT_ID",
  "GOOGLE_CLIENT_SECRET",
  "GEMINI_API_KEY",
  "OLLAMA_BASE_URL",
]);

const body = readFileSync(templatePath, "utf8");

const rendered = body
  .split("\n")
  .map((line) => {
    const match = /^([A-Z0-9_]+)=(.*)$/.exec(line);
    if (!match) return line;
    const [, key] = match;
    if (key === "GOLIATH_TOKEN_ENCRYPTION_KEY") return `${key}=${encryptionKey}`;
    if (blank.has(key)) return `${key}=`;
    return line;
  })
  .join("\n");

const header = [
  "# Generated by scripts/generate-env.mjs",
  "# GOLIATH_TOKEN_ENCRYPTION_KEY is real (32 random bytes, base64) and safe for local use.",
  "# Blank keys below must be filled from your own Supabase and Google Cloud accounts.",
  "",
].join("\n");

writeFileSync(target, header + rendered, { mode: 0o600 });

console.log("Wrote .env.local");
console.log("  GOLIATH_TOKEN_ENCRYPTION_KEY: generated");
console.log("  Supabase + Google credentials: left blank on purpose");
console.log("");
console.log("Next: node scripts/check-env.mjs");